bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case ALT_TAB:
            if (record->event.pressed) {
              if (!kb_get_alt_tab_state()) {
                kb_set_alt_tab_active();
                register_code(KC_LGUI);
              }
              alt_tab_timer = timer_read();
              register_code(KC_TAB);
            } else {
              unregister_code(KC_TAB);
            }
            break;
        case SFT_ALT_TAB:
            if (record->event.pressed) {
              if (!kb_get_alt_tab_state()) {
                kb_set_alt_tab_active();
                register_code(KC_LGUI);
              }
              alt_tab_timer = timer_read();
              register_code(KC_LSFT);
              register_code(KC_TAB);
            } else {
              unregister_code(KC_TAB);
              unregister_code(KC_LSFT);
            }
            break;
        case SUP_ALT_TAB:
            if (record->event.pressed) {
              if (!kb_get_super_alt_tab_state()) {
                kb_set_super_alt_tab_active();
                register_code(KC_LGUI);
              }
              sup_alt_tab_timer = timer_read();
              register_code(KC_TAB);
            } else {
              unregister_code(KC_TAB);
            }
            break;
        case LT(0,KC_YAY):
            if (record->event.pressed) {
                SEND_STRING("\\o/");
                return false;
            }
            return true;
        case LT(0,KC_N):
            if (!record->tap.count && record->event.pressed) {
                tap_code16(LCMD(LSFT(KC_N))); // hold for command+letter
                return false;
            }
            return true;
        case LT(0,KC_MPLY):
            if (!record->tap.count && record->event.pressed) {
                tap_code16(KC_MNXT); // hold for command+letter
                return false;
            }
            return true;
        case KC_PD_LAYER:
            if (record->event.pressed) {
                // xprintf("KC_PD_LAYER pressed\n");
                #if defined(RAW_ENABLE)
                    cycle_pedal_layer();
                #endif
                return false;
            }
            return true;
        case KC_FINDER:
            if (record->event.pressed) {
                tap_code16(LCMD(KC_SPACE));
                return false;
            }
            return true;
        case AM_Toggle:
            if(record->event.pressed) { // key down
                auto_mouse_toggle();
                return false;
            } // do nothing on key up
            return true; // prevent further processing of keycode
    }
    return true;
}

void matrix_scan_user(void) {
  if (kb_get_alt_tab_state()) {
    if (timer_elapsed(alt_tab_timer) > 1000) {
      kb_set_alt_tab_off();
      unregister_code(KC_LGUI);
    }
  }
  if (kb_get_super_alt_tab_state()) {
    if (timer_elapsed(sup_alt_tab_timer) > 50) {
      kb_set_super_alt_tab_off();
      unregister_code(KC_LGUI);
    }
  }
}

layer_state_t layer_state_set_user(layer_state_t state) {
    #if defined(RAW_ENABLE)
        xprintf("Layer changed to: %u\n", state);
        send_wled_layer(state);
    #endif
    return state;
}